#!/usr/bin/env python3
"""Host end-to-end check of the D5 Proof-of-Play API: starts a REAL vm_api_server (mock embedding provider), registers two
media, builds references, schedules sessions, feeds the event adapter a JSONL file written in the BrightScript event format
and checks the verification verdicts, evidence storage, exports and HTTP policy.

  vm_pop_e2e.py /path/to/vm_api_server

HOST ONLY / SYNTHETIC: the events and screenshots here are generated by this script to test the plumbing (adapter, store,
API). They are NOT hardware evidence; the XT5 results come from the real player (docs/test_results/d5_*).
Exit code 0 = all checks passed.
"""
import json, os, shutil, signal, subprocess, sys, tempfile, time, urllib.error, urllib.request
from PIL import Image, ImageDraw

BIN = sys.argv[1]
PORT = 20431
BASE = f"http://127.0.0.1:{PORT}"
fails = []


def check(name, cond, extra=""):
    print(("PASS " if cond else "FAIL ") + name + ((" -- " + str(extra)) if extra and not cond else ""))
    if not cond:
        fails.append(name)


def call(method, path, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(BASE + path, data=data, method=method, headers={"Content-Type": "application/json"} if data else {})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            b = r.read(); ct = r.headers.get("Content-Type", "")
            return r.status, (json.loads(b) if "json" in ct else b), ct
    except urllib.error.HTTPError as e:
        b = e.read(); ct = e.headers.get("Content-Type", "")
        return e.code, (json.loads(b) if "json" in ct else b), ct


def picture(kind, w, h, shift=0, bright=0):
    """Deterministic smooth pictures: kind 'A' and 'B' differ in structure; shift/bright mimic a different capture of the same content."""
    im = Image.new("RGB", (w, h))
    px = im.load()
    for y in range(h):
        for x in range(w):
            xn, yn = (x + shift) / w, y / h
            if kind == "A":
                px[x, y] = (int(40 + 200 * xn), int(220 - 150 * yn), 90 + int(60 * abs(xn - 0.5)))
            else:
                px[x, y] = (200 if (int(xn * 8) % 2) else 30, 40 + int(180 * abs(yn - 0.5) * 2), 220 if (int(yn * 6) % 2) else 60)
    d = ImageDraw.Draw(im)
    if kind == "A": d.ellipse([w * 0.3, h * 0.2, w * 0.7, h * 0.8], outline=(255, 255, 255), width=4)
    else: d.rectangle([w * 0.2, h * 0.3, w * 0.8, h * 0.7], fill=(250, 250, 40))
    if bright: im = im.point(lambda v: max(0, min(255, v + bright)))
    return im


tmp = tempfile.mkdtemp(prefix="pop_e2e_")
root = os.path.join(tmp, "store"); sd = os.path.join(tmp, "sd"); os.makedirs(os.path.join(sd, "pop", "shots")); os.makedirs(os.path.join(sd, "pop", "jobs"))
events = os.path.join(sd, "pop", "events.jsonl")
open(events, "w").close()
cfg = {"visual_memory": {"enabled": True, "vector_search_enabled": True, "storage_root": root, "embedding": {"enabled": True},
                         "pop": {"enabled": True, "events_path": events, "jobs_dir": os.path.join(sd, "pop", "jobs"), "poll_ms": 50,
                                 "sd_path_prefix_from": "SD:/", "sd_path_prefix_to": sd + "/", "allow_test_jobs": True}}}
cfgp = os.path.join(tmp, "cfg.json"); json.dump(cfg, open(cfgp, "w"))
os.makedirs(root, exist_ok=True)
srv = subprocess.Popen([BIN, "--config", cfgp, "--port", str(PORT), "--provider", "mock:64", "--status-file", os.path.join(tmp, "st.json")],
                       stderr=open(os.path.join(tmp, "srv.log"), "w"))
try:
    for _ in range(50):
        try: urllib.request.urlopen(BASE + "/api/pop/status", timeout=1); break
        except Exception: time.sleep(0.1)

    st, s, _ = call("GET", "/api/pop/status")
    check("status: enabled, adapter running, schema 1", st == 200 and s["enabled"] and s["adapter"]["running"] and s["store"]["schema_version"] == 1, s)
    check("status states the evidence source is the presentation output", "presentation output" in s["evidence_source"])

    # ---- reference library
    for mid, name in (("ad-a", "Advertisement A"), ("ad-b", "Advertisement B")):
        st, r, _ = call("POST", "/api/pop/media", {"media_id": mid, "display_name": name, "uri": mid + ".mp4", "duration_s": 60, "slot_s": 30, "width": 1920, "height": 1080})
        check(f"register {mid} -> 201", st == 201 and r["reference_frames"] == 0, r)
        d = os.path.join(root, "pop", "refs_incoming", mid); os.makedirs(d)
        for i in range(8): picture(mid[-1].upper(), 640, 400, shift=i * 4).save(os.path.join(d, f"{i * 4000}.jpg"), quality=90)
        st, r, _ = call("POST", f"/api/pop/media/{mid}/references/build")
        check(f"build references {mid}: 8 added", st == 200 and r["added"] == 8 and r["failed"] == 0, r)
    st, r, _ = call("POST", "/api/pop/media", {"media_id": "../bad", "uri": "x"})
    check("register: bad media_id rejected", st == 400, r)
    st, r, _ = call("GET", "/api/pop/media")
    check("media list has both with 8 references", st == 200 and {m["media_id"]: m["reference_frames"] for m in r["media"]} == {"ad-a": 8, "ad-b": 8}, r)
    st, r, _ = call("POST", "/api/pop/media/ad-a/references/build")
    check("build with no incoming files -> 404", st == 404, r)

    # ---- scheduling
    st, r, _ = call("POST", "/api/pop/sessions", {"expected_media_id": "ad-a", "session_id": "t-a"})
    check("schedule -> 201 with a job file", st == 201 and r["capture_offsets_ms"] == [3000, 15000, 27000], r)
    job = json.load(open(os.path.join(sd, "pop", "jobs", r["job_file"])))
    check("job file content", job["media_file"] == "ad-a.mp4" and job["max_play_ms"] == 30000 and job["media_id"] == "ad-a" and job["loop"] is False, job)
    st, r2, _ = call("POST", "/api/pop/sessions", {"expected_media_id": "ad-a", "session_id": "t-a"})
    check("duplicate session id -> 409", st == 409, r2)
    st, r2, _ = call("POST", "/api/pop/sessions", {"expected_media_id": "nope"})
    check("unknown media -> 404", st == 404, r2)
    st, r2, _ = call("POST", "/api/pop/sessions", {"expected_media_id": "ad-a", "capture_offsets_s": [99]})
    check("offset beyond the slot -> 400", st == 400, r2)
    st, d, _ = call("GET", "/api/pop/sessions/t-a")
    check("scheduled session reads back as Scheduled", st == 200 and d["status"] == "scheduled" and d["status_label"] == "Scheduled", d)
    for sid, kw in (("t-b", {"play_media_id": "ad-b"}), ("t-c", {"interrupt_at_s": 10}), ("t-d", {"break_capture": True})):
        st, r2, _ = call("POST", "/api/pop/sessions", dict({"expected_media_id": "ad-a", "session_id": sid}, **kw))
        check(f"schedule {sid} (test hook) -> 201", st == 201, r2)
    jb = json.load(open(os.path.join(sd, "pop", "jobs", [f for f in os.listdir(os.path.join(sd, "pop", "jobs")) if f.endswith("t-b.json")][0])))
    check("wrong-ad job plays ad-b but expects ad-a", jb["media_id"] == "ad-b" and jb["expected_media_id"] == "ad-a" and jb["media_file"] == "ad-b.mp4", jb)
    jd = json.load(open(os.path.join(sd, "pop", "jobs", [f for f in os.listdir(os.path.join(sd, "pop", "jobs")) if f.endswith("t-d.json")][0])))
    check("break_capture sends screenshots to an unwritable directory", jd["capture_dir"].endswith("no_such_dir"), jd)

    # ---- events in the player's format (mono clock only), screenshots as files on the "SD card"
    mono = [0]
    seq = [0]

    def emit(ev, **kw):
        seq[0] += 1
        e = {"ev": ev, "seq": seq[0], "mono_ms": kw.pop("mono_ms"), **kw}
        with open(events, "a") as f: f.write(json.dumps(e) + "\n")

    def shot(sid, idx, kind, off, shift=0, bright=0):
        fn = f"{sid}_{idx}.jpg"
        picture(kind, 640, 400, shift=shift, bright=bright).save(os.path.join(sd, "pop", "shots", fn), quality=85)
        emit("capture_ok", session=sid, media_id="x", expected_media_id="ad-a", idx=idx, file=f"SD:/pop/shots/{fn}", target_offset_ms=off,
             actual_offset_ms=off + 6, took_ms=300, width=640, height=400, mono_ms=mono[0] + off)

    def play(sid, media, actual, reason, t0, interrupt=False):
        emit("session_scheduled_run", session=sid, job_id="job-" + sid, media_id=media, expected_media_id="ad-a", capture_count=3, mono_ms=t0)
        emit("play_requested", session=sid, media_id=media, expected_media_id="ad-a", ok=True, mono_ms=t0 + 5)
        emit("play_started", session=sid, media_id=media, expected_media_id="ad-a", vcode=3, latency_ms=270, mono_ms=t0 + 280)
        return t0 + 280

    emit("boot", mode="jobs", mono_ms=4)
    # Test A: correct ad (same pictures, different capture offsets / brightness)
    t = play("t-a", "ad-a", 30100, "slot_end", 1000)
    for i, off in enumerate((3000, 15000, 27000), 1): shot("t-a", i, "A", off, shift=i * 5, bright=6)
    emit("play_stopped", session="t-a", media_id="ad-a", reason="slot_end", mono_ms=t + 30020)
    emit("session_end", session="t-a", media_id="ad-a", expected_media_id="ad-a", reason="slot_end", actual_play_ms=30105, mono_ms=t + 30030)
    # Test B: the display shows ad B
    t = play("t-b", "ad-b", 30100, "slot_end", 40000)
    for i, off in enumerate((3000, 15000, 27000), 1): shot("t-b", i, "B", off, shift=i * 3)
    emit("session_end", session="t-b", media_id="ad-b", expected_media_id="ad-a", reason="slot_end", actual_play_ms=30090, mono_ms=t + 30030)
    # Test C: interrupted after 10 s, one screenshot taken
    t = play("t-c", "ad-a", 10000, "interrupted", 80000)
    shot("t-c", 1, "A", 3000, shift=4)
    emit("play_stopped", session="t-c", media_id="ad-a", reason="interrupted", mono_ms=t + 10020)
    emit("session_end", session="t-c", media_id="ad-a", expected_media_id="ad-a", reason="interrupted", actual_play_ms=10015, mono_ms=t + 10030)
    # Test D: every Screenshot() call fails
    t = play("t-d", "ad-a", 30100, "slot_end", 120000)
    for i, off in enumerate((3000, 15000, 27000), 1):
        emit("capture_failed", session="t-d", media_id="ad-a", expected_media_id="ad-a", idx=i, file="SD:/pop/no_such_dir/t-d_%d.jpg" % i, target_offset_ms=off,
             actual_offset_ms=off + 4, took_ms=2, reason="", mono_ms=t + off)
    emit("session_end", session="t-d", media_id="ad-a", expected_media_id="ad-a", reason="slot_end", actual_play_ms=30100, mono_ms=t + 30030)

    def wait_status(sid, want, timeout=15):
        t0 = time.time(); d = None
        while time.time() - t0 < timeout:
            st, d, _ = call("GET", f"/api/pop/sessions/{sid}")
            if st == 200 and d["status"] == want: return d
            time.sleep(0.2)
        return d

    d = wait_status("t-a", "playback_corroborated")
    check("Test A: Playback corroborated", d["status"] == "playback_corroborated", d.get("status") and (d["status"], d["reason"]))
    check("Test A: 3 screenshots stored, 3 matched, similarity high", d["verification"]["frames_ok"] == 3 and d["verification"]["frames_matched"] == 3 and d["verification"]["min_sim_expected"] > 0.8, d.get("verification"))
    check("Test A: session timing from the events", d["actual_play_ms"] == 30105 and d["end_reason"] == "slot_end" and d["start_utc_ms"] > 1.7e12, d)
    ev = d["evidence"]
    check("evidence stored in hourly partitions", all(e["image_available"] for e in ev), ev)
    st, img, ct = call("GET", ev[0]["image_url"])
    check("evidence image served as JPEG", st == 200 and ct == "image/jpeg" and img[:3] == b"\xff\xd8\xff", (st, ct))
    check("source screenshot moved into the evidence store", not os.path.exists(os.path.join(sd, "pop", "shots", "t-a_1.jpg")))
    check("reference frames listed for comparison", len(d["reference_frames"]) == 8)
    st, ri, ct = call("GET", d["reference_frames"][0]["image_url"])
    check("reference image served", st == 200 and ct == "image/jpeg")

    d = wait_status("t-b", "mismatch")
    check("Test B: Mismatch naming the other media", d["status"] == "mismatch" and "ad-b" in d["reason"] and d["verification"]["best_media_id"] == "ad-b", (d["status"], d["reason"]))
    d = wait_status("t-c", "incomplete")
    check("Test C: Incomplete (interrupted)", d["status"] == "incomplete" and d["end_reason"] == "interrupted", (d["status"], d["reason"]))
    d = wait_status("t-d", "capture_unsupported")
    check("Test D: Capture unsupported, playback reported", d["status"] == "capture_unsupported" and d["verification"]["frames_failed"] == 3, (d["status"], d["reason"]))
    check("Test D: failed captures recorded without images", [e["status"] for e in d["evidence"]] == ["failed"] * 3 and not any(e["image_available"] for e in d["evidence"]))
    hp = [os.path.join(dp, f) for dp, _, fs in os.walk(os.path.join(root, "pop", "evidence")) for f in fs]
    import re
    check("hourly layout pop/evidence/YYYY/MM/DD/HH/main_display/ (7 images: A 3, B 3, C 1)", len(hp) == 7 and all(re.search(r"pop/evidence/\d{4}/\d\d/\d\d/\d\d/main_display/[^/]+\.jpg$", p) for p in hp), hp[:2])

    # ---- listing, filters, export, re-verify, policy
    st, l, _ = call("GET", "/api/pop/sessions?limit=10")
    check("history lists all four", st == 200 and l["total"] == 4 and {x["status"] for x in l["sessions"]} == {"playback_corroborated", "mismatch", "incomplete", "capture_unsupported"}, l)
    st, l, _ = call("GET", "/api/pop/sessions?status=mismatch")
    check("filter by status", st == 200 and l["total"] == 1 and l["sessions"][0]["session_id"] == "t-b", l)
    st, l, _ = call("GET", "/api/pop/sessions?status=bogus")
    check("unknown status filter -> 400", st == 400)
    st, c, ct = call("GET", "/api/pop/sessions/export.csv")
    lines = c.decode().strip().splitlines()
    check("CSV export: header + 4 rows", st == 200 and ct.startswith("text/csv") and len(lines) == 5 and lines[0].startswith("session_id,"), lines[:2])
    st, r, _ = call("POST", "/api/pop/sessions/t-a/verify")
    check("re-verify keeps the verdict", st == 200 and r["status"] == "playback_corroborated", r)
    st, r, _ = call("POST", "/api/pop/sessions/none/verify")
    check("verify unknown session -> 404", st == 404)
    st, r, _ = call("GET", "/api/pop/sessions/../x")
    check("path traversal id rejected", st in (400, 404), st)
    st, r, _ = call("DELETE", "/api/pop/sessions/t-a")
    check("DELETE not supported -> 405", st == 405)
    st, r, _ = call("GET", "/api/pop/sessions/t-a/evidence/999999/image")
    check("evidence id of another session -> 404", st == 404)
    st, s, _ = call("GET", "/api/pop/status")
    check("adapter counters", s["adapter"]["events_ingested"] > 20 and s["adapter"]["errors"] == 0 and s["store"]["evidence"] == 10, s["adapter"])

    # ---- a screenshot file that is still being written (Screenshot() returns before the JPEG is complete on the XT5)
    import threading
    t = play("t-race", "ad-a", 30100, "slot_end", 200000)
    full = os.path.join(sd, "pop", "shots", "full.jpg"); picture("A", 640, 400, shift=7).save(full, quality=85)
    data = open(full, "rb").read()
    p1 = os.path.join(sd, "pop", "shots", "t-race_1.jpg"); p2 = os.path.join(sd, "pop", "shots", "t-race_2.jpg")
    open(p1, "wb").write(data[:3000]); open(p2, "wb").write(data[:3000])          # truncated: no EOI marker yet
    for i in (1, 2):
        emit("capture_ok", session="t-race", media_id="ad-a", expected_media_id="ad-a", idx=i, file=f"SD:/pop/shots/t-race_{i}.jpg", target_offset_ms=3000 * i,
             actual_offset_ms=3000 * i, took_ms=300, mono_ms=t + 3000 * i)
    threading.Timer(0.6, lambda: open(p1, "wb").write(data)).start()               # idx 1 completes shortly after; idx 2 never does
    emit("session_end", session="t-race", media_id="ad-a", expected_media_id="ad-a", reason="slot_end", actual_play_ms=30100, mono_ms=t + 30030)
    d = wait_status("t-race", "playback_reported", 30)
    ev = {e["idx"]: e for e in d["evidence"]}
    check("race: a file completed within the wait is ingested", ev.get(1, {}).get("status") == "ok", d["evidence"])
    check("race: a file that never completes is recorded as a failed capture (not lost)", ev.get(2, {}).get("status") == "failed" and "incomplete" in ev[2]["failure_reason"], d["evidence"])

    # ---- live sources: references can be refreshed instead of accumulating stale scenes
    d = os.path.join(root, "pop", "refs_incoming", "ad-b"); os.makedirs(d, exist_ok=True)
    for i in range(3): picture("B", 640, 400, shift=i * 9).save(os.path.join(d, f"{i * 1000}.jpg"), quality=90)
    st, r, _ = call("POST", "/api/pop/media/ad-b/references/build?replace=1")
    check("build with replace=1 swaps the reference set (8 -> 3)", st == 200 and r["added"] == 3 and r["reference_frames"] == 3, r)

    # ---- adapter survives a restart without re-ingesting
    srv.send_signal(signal.SIGTERM); srv.wait(timeout=10)
    srv = subprocess.Popen([BIN, "--config", cfgp, "--port", str(PORT), "--provider", "mock:64", "--status-file", os.path.join(tmp, "st.json")], stderr=open(os.path.join(tmp, "srv2.log"), "w"))
    for _ in range(50):
        try: urllib.request.urlopen(BASE + "/api/pop/status", timeout=1); break
        except Exception: time.sleep(0.1)
    time.sleep(0.6)
    st, s, _ = call("GET", "/api/pop/status")
    check("restart: offset persisted, nothing re-ingested", s["store"]["events"] > 24, s["store"])
    n_events = s["store"]["events"]
    emit("video_event", session="t-a", media_id="ad-a", vcode=3, mono_ms=999999)
    time.sleep(0.6)
    st, s, _ = call("GET", "/api/pop/status")
    check("restart: only the new line is ingested", s["store"]["events"] == n_events + 1, (n_events, s["store"]["events"]))

    if "--hold" in sys.argv:                       # keep the seeded stack up for the browser test (tests/browser/d5_ui_cdp.py)
        secs = int(sys.argv[sys.argv.index("--hold") + 1]) if len(sys.argv) > sys.argv.index("--hold") + 1 else 60
        print("HOLD %d s: API on %s" % (secs, BASE), flush=True)
        time.sleep(secs)
finally:
    srv.terminate()
    try: srv.wait(timeout=5)
    except Exception: srv.kill()
    log = open(os.path.join(tmp, "srv.log")).read()
    if fails: print("server log tail:\n" + log[-1500:])
    shutil.rmtree(tmp, ignore_errors=True)

print("\n%s: %d check(s) failed" % ("FAIL" if fails else "OK", len(fails)))
sys.exit(1 if fails else 0)
